//! Parsing and code generation for `design/tokens.json`.

use std::fmt::Write as _;

use serde_json::{Map, Value};

const HEADER: &str = "Generated by `cargo run -p gen-tokens` from design/tokens.json. Do not edit.";

/// An sRGB colour with alpha, as written in tokens.json (`#RRGGBB` or `rgba(r,g,b,a)`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Rgba {
    pub r: u8,
    pub g: u8,
    pub b: u8,
    pub a: f64,
}

impl Rgba {
    /// Parses `#RRGGBB` or `rgba(r,g,b,a)`.
    pub fn parse(s: &str) -> Result<Self, String> {
        let s = s.trim();
        if let Some(hex) = s.strip_prefix('#') {
            if hex.len() != 6 {
                return Err(format!("expected #RRGGBB, got {s}"));
            }
            let byte =
                |i: usize| u8::from_str_radix(&hex[i..i + 2], 16).map_err(|e| format!("{s}: {e}"));
            return Ok(Self {
                r: byte(0)?,
                g: byte(2)?,
                b: byte(4)?,
                a: 1.0,
            });
        }
        let inner = s
            .strip_prefix("rgba(")
            .and_then(|r| r.strip_suffix(')'))
            .ok_or_else(|| format!("unsupported colour {s}"))?;
        let parts: Vec<&str> = inner.split(',').map(str::trim).collect();
        let [r, g, b, a] = parts.as_slice() else {
            return Err(format!("expected 4 components in {s}"));
        };
        let chan = |v: &str| v.parse::<u8>().map_err(|e| format!("{s}: {e}"));
        let a: f64 = a.parse().map_err(|e| format!("{s}: {e}"))?;
        if !(0.0..=1.0).contains(&a) {
            return Err(format!("alpha out of range in {s}"));
        }
        Ok(Self {
            r: chan(r)?,
            g: chan(g)?,
            b: chan(b)?,
            a,
        })
    }

    /// Flutter `Color` literal, `0xAARRGGBB`.
    pub fn dart_hex(&self) -> String {
        let a = (self.a * 255.0).round() as u8;
        format!("0x{a:02X}{:02X}{:02X}{:02X}", self.r, self.g, self.b)
    }

    /// CSS colour value.
    pub fn css(&self) -> String {
        if (self.a - 1.0).abs() < f64::EPSILON {
            format!("#{:02X}{:02X}{:02X}", self.r, self.g, self.b)
        } else {
            format!(
                "rgba({}, {}, {}, {})",
                self.r,
                self.g,
                self.b,
                trim_float(self.a)
            )
        }
    }
}

/// One typography role.
#[derive(Debug, Clone, PartialEq)]
pub struct TypeRole {
    pub mono: bool,
    pub weight: u16,
    pub size: f64,
    pub line_height: f64,
    pub letter_spacing_em: f64,
}

type NumberGroups = Vec<(String, Vec<(String, f64)>)>;

/// Parsed contents of tokens.json. Maps keep the file's key order.
#[derive(Debug, Clone)]
pub struct Tokens {
    pub font_sans: String,
    pub font_mono: String,
    /// Colour roles, `(name, dark, light)`. Both themes must define the same roles.
    pub colors: Vec<(String, Rgba, Rgba)>,
    pub placeholder_dark: Vec<(Rgba, Rgba)>,
    pub placeholder_light: Vec<(Rgba, Rgba)>,
    /// Shadows, `(name, dark css, light css)`.
    pub shadows: Vec<(String, String, String)>,
    /// Numeric groups (`radius`, `space`, `size`, `wheel`), each `(name, value)`.
    pub numbers: NumberGroups,
    pub types: Vec<(String, TypeRole)>,
    desktop: DesktopTokens,
}

#[derive(Debug, Clone)]
struct DesktopTokens {
    colors: Vec<(String, Rgba, Rgba)>,
    numbers: NumberGroups,
    types: Vec<(String, TypeRole)>,
}

fn obj<'a>(v: &'a Value, key: &str) -> Result<&'a Map<String, Value>, String> {
    v.get(key)
        .and_then(Value::as_object)
        .ok_or_else(|| format!("missing object `{key}`"))
}

fn str_of<'a>(v: &'a Value, what: &str) -> Result<&'a str, String> {
    v.as_str()
        .ok_or_else(|| format!("`{what}` must be a string"))
}

fn num_of(v: &Value, what: &str) -> Result<f64, String> {
    v.as_f64()
        .ok_or_else(|| format!("`{what}` must be a number"))
}

fn is_meta(key: &str) -> bool {
    key.starts_with('$')
}

fn color_roles(root: &Value) -> Result<Vec<(String, Rgba, Rgba)>, String> {
    let color = obj(root, "color")?;
    let dark = obj(&Value::Object(color.clone()), "dark")?.clone();
    let light = obj(&Value::Object(color.clone()), "light")?.clone();
    let mut colors = Vec::new();
    for (name, dv) in &dark {
        let lv = light
            .get(name)
            .ok_or_else(|| format!("color.light is missing `{name}`"))?;
        colors.push((
            name.clone(),
            Rgba::parse(str_of(dv, name)?)?,
            Rgba::parse(str_of(lv, name)?)?,
        ));
    }
    if let Some(extra) = light.keys().find(|k| !dark.contains_key(*k)) {
        return Err(format!("color.dark is missing `{extra}`"));
    }
    Ok(colors)
}

fn number_groups(root: &Value, groups: &[&str]) -> Result<NumberGroups, String> {
    let mut numbers = Vec::new();
    for &group in groups {
        let mut items = Vec::new();
        for (k, v) in obj(root, group)? {
            if !is_meta(k) {
                items.push((k.clone(), num_of(v, k)?));
            }
        }
        numbers.push((group.to_owned(), items));
    }
    Ok(numbers)
}

fn type_roles(root: &Value) -> Result<Vec<(String, TypeRole)>, String> {
    let mut types = Vec::new();
    for (name, v) in obj(root, "type")? {
        if is_meta(name) {
            continue;
        }
        let a = v.as_array().filter(|a| a.len() == 5).ok_or_else(|| {
            format!("type.{name} must be [family, weight, size, lineHeight, letterSpacingEm]")
        })?;
        let family = str_of(&a[0], name)?;
        if family != "sans" && family != "mono" {
            return Err(format!("type.{name}: family must be 'sans' or 'mono'"));
        }
        types.push((
            name.clone(),
            TypeRole {
                mono: family == "mono",
                weight: num_of(&a[1], name)? as u16,
                size: num_of(&a[2], name)?,
                line_height: num_of(&a[3], name)?,
                letter_spacing_em: num_of(&a[4], name)?,
            },
        ));
    }
    Ok(types)
}

impl Tokens {
    /// Parses and validates tokens.json.
    pub fn parse(source: &str) -> Result<Self, String> {
        let root: Value = serde_json::from_str(source).map_err(|e| e.to_string())?;

        let font = obj(&root, "font")?;
        let font_sans = str_of(font.get("sans").unwrap_or(&Value::Null), "font.sans")?.to_owned();
        let font_mono = str_of(font.get("mono").unwrap_or(&Value::Null), "font.mono")?.to_owned();

        let colors = color_roles(&root)?;

        let art = obj(&root, "placeholderArt")?;
        let pairs = |theme: &str| -> Result<Vec<(Rgba, Rgba)>, String> {
            let list = art
                .get(theme)
                .and_then(Value::as_array)
                .ok_or_else(|| format!("placeholderArt.{theme} must be an array"))?;
            if list.len() != 6 {
                return Err(format!("placeholderArt.{theme} needs exactly 6 pairs"));
            }
            list.iter()
                .map(|p| {
                    let p = p
                        .as_array()
                        .filter(|p| p.len() == 2)
                        .ok_or("pair must be [fill, caption]")?;
                    Ok((
                        Rgba::parse(str_of(&p[0], "fill")?)?,
                        Rgba::parse(str_of(&p[1], "caption")?)?,
                    ))
                })
                .collect()
        };
        let placeholder_dark = pairs("dark")?;
        let placeholder_light = pairs("light")?;

        let shadow = obj(&root, "shadow")?;
        let sd = shadow
            .get("dark")
            .and_then(Value::as_object)
            .ok_or("missing shadow.dark")?;
        let sl = shadow
            .get("light")
            .and_then(Value::as_object)
            .ok_or("missing shadow.light")?;
        let mut shadows = Vec::new();
        for (name, dv) in sd {
            let lv = sl
                .get(name)
                .ok_or_else(|| format!("shadow.light is missing `{name}`"))?;
            shadows.push((
                name.clone(),
                str_of(dv, name)?.to_owned(),
                str_of(lv, name)?.to_owned(),
            ));
        }

        let numbers = number_groups(&root, &["radius", "space", "size", "wheel"])?;
        let types = type_roles(&root)?;

        let desktop = root.get("desktop").ok_or("missing desktop tokens")?;
        let desktop = DesktopTokens {
            colors: color_roles(desktop)?,
            numbers: number_groups(desktop, &["radius", "space", "size"])?,
            types: type_roles(desktop)?,
        };

        Ok(Self {
            font_sans,
            font_mono,
            colors,
            placeholder_dark,
            placeholder_light,
            shadows,
            numbers,
            types,
            desktop,
        })
    }

    /// Looks up a number by group and name.
    pub fn number(&self, group: &str, name: &str) -> Option<f64> {
        self.numbers
            .iter()
            .find(|(g, _)| g == group)
            .and_then(|(_, items)| items.iter().find(|(n, _)| n == name).map(|(_, v)| *v))
    }

    /// Looks up a colour role, returning `(dark, light)`.
    pub fn color(&self, name: &str) -> Option<(Rgba, Rgba)> {
        self.colors
            .iter()
            .find(|(n, ..)| n == name)
            .map(|(_, d, l)| (*d, *l))
    }
}

fn trim_float(v: f64) -> String {
    let s = format!("{v:.4}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s.is_empty() || s == "-" {
        "0".to_owned()
    } else {
        s.to_owned()
    }
}

fn kebab(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            out.push('-');
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn upper_first(name: &str) -> String {
    let mut c = name.chars();
    match c.next() {
        Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

/// CSS custom properties for the desktop app. Light is the default; dark applies
/// under `prefers-color-scheme: dark` unless `data-theme="light"` is set, and
/// whenever `data-theme="dark"` is set.
pub fn css(t: &Tokens) -> String {
    let mut s = format!("/* {HEADER} */\n\n:root {{\n");
    let _ = writeln!(
        s,
        "  --mt-font-sans: \"{}\", system-ui, sans-serif;",
        t.font_sans
    );
    let _ = writeln!(
        s,
        "  --mt-font-mono: \"{}\", ui-monospace, monospace;",
        t.font_mono
    );
    css_numbers_and_type(&mut s, "mt", &t.numbers, &t.types);
    css_numbers_and_type(&mut s, "mt-desktop", &t.desktop.numbers, &t.desktop.types);
    s.push_str(&theme_block(t, false));
    s.push_str("}\n\n");

    let dark = theme_block(t, true);
    let _ = write!(
        s,
        "@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{}  }}\n}}\n\n:root[data-theme=\"dark\"] {{\n{dark}}}\n",
        indent(&dark)
    );
    s
}

fn css_numbers_and_type(
    s: &mut String,
    prefix: &str,
    numbers: &[(String, Vec<(String, f64)>)],
    types: &[(String, TypeRole)],
) {
    for (group, items) in numbers {
        for (name, v) in items {
            let unit = if group == "wheel"
                && (name.ends_with("Deg") || name.ends_with("Degrees") || name.ends_with("Stop"))
            {
                ""
            } else {
                "px"
            };
            let _ = writeln!(
                s,
                "  --{prefix}-{group}-{}: {}{unit};",
                kebab(name),
                trim_float(*v)
            );
        }
    }
    for (name, role) in types {
        let fam = if role.mono {
            "var(--mt-font-mono)"
        } else {
            "var(--mt-font-sans)"
        };
        let _ = writeln!(
            s,
            "  --{prefix}-type-{}: {} {}px/{} {fam};",
            kebab(name),
            role.weight,
            trim_float(role.size),
            trim_float(role.line_height)
        );
        let _ = writeln!(
            s,
            "  --{prefix}-type-{}-tracking: {}em;",
            kebab(name),
            trim_float(role.letter_spacing_em)
        );
    }
}

fn indent(block: &str) -> String {
    block.lines().map(|l| format!("  {l}\n")).collect()
}

fn theme_block(t: &Tokens, dark: bool) -> String {
    let mut s = String::new();
    for (prefix, colors) in [("mt", &t.colors), ("mt-desktop", &t.desktop.colors)] {
        for (name, d, l) in colors {
            let c = if dark { d } else { l };
            let _ = writeln!(s, "  --{prefix}-{}: {};", kebab(name), c.css());
        }
    }
    let art = if dark {
        &t.placeholder_dark
    } else {
        &t.placeholder_light
    };
    for (i, (fill, caption)) in art.iter().enumerate() {
        let _ = writeln!(s, "  --mt-art-{i}-fill: {};", fill.css());
        let _ = writeln!(s, "  --mt-art-{i}-caption: {};", caption.css());
    }
    for (name, d, l) in &t.shadows {
        let _ = writeln!(
            s,
            "  --mt-shadow-{}: {};",
            kebab(name),
            if dark { d } else { l }
        );
    }
    let radius = if dark {
        "selectedRowDark"
    } else {
        "selectedRowLight"
    };
    let _ = writeln!(
        s,
        "  --mt-radius-selected-row: var(--mt-radius-{});",
        kebab(radius)
    );
    s
}

/// Dart constants for the mobile app.
pub fn dart(t: &Tokens) -> String {
    let mut s = format!(
        "// {HEADER}\n// ignore_for_file: constant_identifier_names\n// dart format off\n\nimport 'package:flutter/painting.dart';\n\n"
    );

    s.push_str("/// Colour roles for one theme (dark = 1a, light = 2a).\nclass MtColors {\n  const MtColors({\n");
    for (name, ..) in &t.colors {
        let _ = writeln!(s, "    required this.{name},");
    }
    s.push_str("    required this.placeholderArt,\n  });\n\n");
    for (name, ..) in &t.colors {
        let _ = writeln!(s, "  final Color {name};");
    }
    s.push_str("\n  /// Six `(fill, caption)` pairs, indexed by `albumIndex % 6`.\n  final List<(Color, Color)> placeholderArt;\n\n");
    for (theme, dark) in [("dark", true), ("light", false)] {
        let _ = writeln!(s, "  static const {theme} = MtColors(");
        for (name, d, l) in &t.colors {
            let c = if dark { d } else { l };
            let _ = writeln!(s, "    {name}: Color({}),", c.dart_hex());
        }
        s.push_str("    placeholderArt: [\n");
        let art = if dark {
            &t.placeholder_dark
        } else {
            &t.placeholder_light
        };
        for (fill, caption) in art {
            let _ = writeln!(
                s,
                "      (Color({}), Color({})),",
                fill.dart_hex(),
                caption.dart_hex()
            );
        }
        s.push_str("    ],\n  );\n\n");
    }
    s.push_str("}\n\n");

    s.push_str("/// Font families (bundled).\nabstract final class MtFonts {\n");
    let _ = writeln!(s, "  static const sans = '{}';", t.font_sans);
    let _ = writeln!(s, "  static const mono = '{}';", t.font_mono);
    s.push_str("}\n\n");

    for (group, items) in &t.numbers {
        let _ = writeln!(s, "abstract final class Mt{} {{", upper_first(group));
        for (name, v) in items {
            let _ = writeln!(s, "  static const double {name} = {};", dart_double(*v));
        }
        s.push_str("}\n\n");
    }

    s.push_str("/// Typography roles: family, weight, size, line height, letter spacing (em).\nabstract final class MtType {\n");
    for (name, r) in &t.types {
        let fam = if r.mono {
            "MtFonts.mono"
        } else {
            "MtFonts.sans"
        };
        let _ = writeln!(
            s,
            "  static const {name} = TextStyle(fontFamily: {fam}, fontWeight: FontWeight.w{}, fontSize: {}, height: {}, letterSpacing: {});",
            r.weight,
            dart_double(r.size),
            dart_double(r.line_height),
            dart_double(r.size * r.letter_spacing_em)
        );
    }
    s.push_str("}\n");
    s
}

fn dart_double(v: f64) -> String {
    let t = trim_float(v);
    if t.contains('.') { t } else { format!("{t}.0") }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tokens() -> Tokens {
        let src = include_str!("../../../design/tokens.json");
        Tokens::parse(src).expect("tokens.json parses")
    }

    #[test]
    fn handoff_sample_values() {
        let t = tokens();
        let (dark, light) = t.color("accent").expect("accent");
        assert_eq!(dark.css(), "#F0A23C");
        assert_eq!(light.css(), "#2F6DB5");
        assert_eq!(t.number("wheel", "diameter"), Some(252.0));
        assert_eq!(t.number("wheel", "centreButton"), Some(104.0));
        assert_eq!(t.number("wheel", "detentDegrees"), Some(12.0));
        assert_eq!(t.number("radius", "selectedRowLight"), Some(5.0));
    }

    #[test]
    fn colour_parsing() {
        assert_eq!(
            Rgba::parse("#0E1116").map(|c| c.dart_hex()),
            Ok("0xFF0E1116".into())
        );
        let c = Rgba::parse("rgba(240,162,60,0.14)").expect("rgba");
        assert_eq!(c.dart_hex(), "0x24F0A23C");
        assert_eq!(c.css(), "rgba(240, 162, 60, 0.14)");
        assert!(Rgba::parse("#FFF").is_err());
        assert!(Rgba::parse("rgba(1,2,3,2)").is_err());
    }

    #[test]
    fn themes_must_define_the_same_roles() {
        let src = r##"{"font":{"sans":"a","mono":"b"},"color":{"dark":{"x":"#000000"},"light":{}},
            "placeholderArt":{"dark":[],"light":[]},"shadow":{"dark":{},"light":{}},
            "radius":{},"space":{},"size":{},"wheel":{},"type":{}}"##;
        assert!(Tokens::parse(src).unwrap_err().contains("missing `x`"));
    }

    #[test]
    fn generated_files_are_up_to_date() {
        let t = tokens();
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        for (rel, content) in [
            ("apps/desktop/src/theme/tokens.css", css(&t)),
            ("apps/mobile/lib/theme/tokens.g.dart", dart(&t)),
        ] {
            let on_disk = std::fs::read_to_string(root.join(rel)).unwrap_or_default();
            assert!(
                on_disk == content,
                "{rel} is stale; run `cargo run -p gen-tokens`"
            );
        }
    }
}
